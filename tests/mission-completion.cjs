const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const {AppState} = require('../electron/state.cjs');
const {Orchestrator} = require('../electron/orchestrator.cjs');
const root = fs.mkdtempSync(path.join(os.tmpdir(),'imx-completion-'));
const state = new AppState(path.join(root,'state'));
const events = [];
const manager = new Orchestrator({terminalManager:{create(input){return {...input,id:input.title}}}, state, codexPath:'fixture',baseEnv:process.env,worktreesRoot:root,emit:e=>events.push(e)});
manager.planMission = async()=>({strategy:'test',tasks:[{id:'one',role:'Frontend'},{id:'two',role:'Design'}]});
manager.prepareWorkspaces = async mission=>{mission.resultPath=root;mission.agentWorkspaces=mission.plan.tasks.map(()=>({cwd:root}));};
manager.waitForAgentTurns = async (_m, task)=>{await new Promise(resolve=>setTimeout(resolve,task.id==='one'?50:30));return {exit:{status:'done'},output:'ok'}};
manager.commitAgentWork = async()=>({changed:false});
manager.mergeAgentBranches = async()=>{};
manager.finalReview = async()=>'Entrega concluída';
(async()=>{
 const draft=manager.createMission({cwd:root,name:'Site',agentCount:2});
 const first=manager.startMission({missionId:draft.id,brief:'Criar site',agentCount:2});
 assert.ok(first.startedAt);assert.equal(first.metrics,null);
 await manager.executions.get(first.id);await Promise.resolve();
 const done=state.getMission(first.id);
 assert.equal(done.status,'done');assert.equal(done.agentTimings.length,2);
 assert.ok(done.metrics.elapsedMs>=50);assert.ok(done.metrics.estimatedSavedMs>0);
 assert.equal(done.metrics.estimatedSerialMs,done.metrics.elapsedMs+done.metrics.estimatedSavedMs);
 assert.ok(events.some(e=>e.type==='mission:completed'&&e.mission.metrics));
 const next=manager.startMission({missionId:first.id,brief:'Ajustar cor',agentCount:2});
 assert.equal(next.round,2);assert.equal(next.metrics,null);assert.deepEqual(next.agentTimings,[]);
 assert.ok(Date.parse(next.startedAt)>=Date.parse(done.finishedAt));
 await manager.executions.get(first.id);
 console.log('PASS: completed event and persistence include metrics; next round resets timing without measuring project age (simulated agents).');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>fs.rmSync(root,{recursive:true,force:true}));
